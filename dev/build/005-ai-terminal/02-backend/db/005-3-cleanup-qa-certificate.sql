-- ЩО РОБИТЬ
--   Видаляє рівно один рядок із `public.certificates` — той, що з'явився під час
--   наскрізного QA-прогону задачі 005 (тестовий акаунт, `full_name` = 'QA Тест 005',
--   виданий 2026-09-05, курс «AI Термінал»). Це перший і на момент написання
--   ЄДИНИЙ рядок у цій таблиці за всю історію проєкту.
--
-- ЧОМУ САМЕ ТАК
--   1. Політики DELETE на `certificates` не існує взагалі — з клієнта рядок
--      прибрати неможливо (і це правильно: сертифікат не має видалятись
--      діями учня). Тому чистка можлива лише привілейованою сесією.
--   2. Умова навмисно подвійна — ім'я І дата. Ім'я тестове й унікальне, дата
--      відсікає будь-який майбутній рядок з таким самим ім'ям.
--   3. Видалення загорнуте в DO-блок із запобіжником: якщо під умову підпадає
--      не рівно один рядок, транзакція падає з винятком і НІЧОГО не видаляє.
--      Це головний захист від «випадково прибрали чужий документ».
--
-- ⚠️ ВІДКАТ НЕМОЖЛИВИЙ АВТОМАТИЧНО — DELETE незворотний.
--    ПЕРЕД запуском кроку 2 ОБОВ'ЯЗКОВО виконати крок 1 і зберегти його вивід
--    ПОЗА репозиторієм (репозиторій публічний, `public_code` і `user_id` у нього
--    класти не можна). Маючи цей вивід, рядок відновлюється звичайним INSERT —
--    шаблон у кінці файлу.
-- =====================================================================


-- ---------------------------------------------------------------------
-- КРОК 1 · Перевірка перед видаленням (тільки читання).
--          Очікувано: рівно 1 рядок. Вивід зберегти поза репозиторієм.
-- ---------------------------------------------------------------------
select c.id,
       c.user_id,
       c.course_id,
       c.public_code,
       c.full_name,
       c.issued_at,
       (select count(*) from public.certificates) as total_rows_in_table
  from public.certificates c
 where c.full_name = 'QA Тест 005'
   and c.issued_at >= timestamptz '2026-09-05 00:00:00+00'
   and c.issued_at <  timestamptz '2026-09-06 00:00:00+00';


-- ---------------------------------------------------------------------
-- КРОК 2 · Саме видалення. Падає з винятком, якщо рядок не рівно один.
-- ---------------------------------------------------------------------
do $$
declare
  v_n integer;
begin
  select count(*) into v_n
    from public.certificates
   where full_name = 'QA Тест 005'
     and issued_at >= timestamptz '2026-09-05 00:00:00+00'
     and issued_at <  timestamptz '2026-09-06 00:00:00+00';

  if v_n <> 1 then
    raise exception 'Очікував рівно 1 рядок під умову, знайшов %. Нічого не видалено.', v_n;
  end if;

  delete from public.certificates
   where full_name = 'QA Тест 005'
     and issued_at >= timestamptz '2026-09-05 00:00:00+00'
     and issued_at <  timestamptz '2026-09-06 00:00:00+00';

  raise notice 'Видалено рядків: 1';
end
$$;


-- ---------------------------------------------------------------------
-- КРОК 3 · Як перевірити, що застосувалось.
--          Очікувано: matching = 0, total = 0.
-- ---------------------------------------------------------------------
select (select count(*) from public.certificates
         where full_name = 'QA Тест 005')      as matching,
       (select count(*) from public.certificates) as total;


