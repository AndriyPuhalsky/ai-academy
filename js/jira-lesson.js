/* ============================================================================
   012 · js/jira-lesson.js — СЛОВНИК СТОРІНКИ УРОКУ: «МОДУЛЬ» → «УРОК»
   ----------------------------------------------------------------------------
   Підключається ТІЛЬКИ з modules/jira-*.html, одразу ПІСЛЯ js/module.js.

   ЧОМУ ЦЕ ОКРЕМИЙ ФАЙЛ, А НЕ КЛЮЧ У КОНФІЗІ
   -----------------------------------------
   Рішення власника 2026-10-01 (П-3, принцип І-0 «ізоляція — лише додавати»):
   `js/module.js` спільний для 57 сторінок трьох живих курсів, і ключа
   `site.unitWord` ми не заводимо. Курс «Jira з нуля» називає свої сторінки
   УРОКАМИ (так їх звуть усі 23 сторінки, конфіг `map.moduleWord` і лендінг),
   а спільний рендерер пише «Модуль» — і це єдине місце, де курс сам собі
   суперечить.

   ЩО САМЕ ПІДМІНЮЄТЬСЯ
   --------------------
   Рівно текстові вузли у вузлах, які пише js/module.js:
     · `#sidebarNav`   — «N з M модулів завершено» (:190);
     · `#moduleNav`    — картки «← Модуль N», «Далі: Модуль N →», «· скоро» (:286–312);
     · `#completeTitle`— «Модуль позаду?» / «Модуль пройдено!» (:333);
     · `#aiaGate`      — замок: «🔒 Модуль заблоковано», «Спершу заверши Модуль N…»,
                          «Перейти до Модуля N →», «Цей модуль поки заблоковано» (:340–365);
     · `#ariaLive`     — «Модуль заблоковано — спершу заверши попередній.» (:550).

   КОЛИ ПІДМІНЮЄТЬСЯ
   -----------------
   1. один раз синхронно при завантаженні — це ще й прибирає єдиний статичний
      літерал «Модуль позаду?» у розмітці (modules/jira-07.html, решта 22 файли
      кажуть «Урок позаду?»; розмітка заморожена, тому в файл не лізем);
   2. на кожній мутації — через `MutationObserver`. Його колбеки виконуються
      МІКРОЗАДАЧЕЮ, тобто до paint: людина не побачить «Модуль» ні на кадр;
   3. додатково на `aia:progress` і `aia:config-ready` — дешева страховка на
      випадок, якщо MutationObserver недоступний.

   ЗБІЙ = «МОДУЛЬ», А НЕ ПОЛОМКА
   -----------------------------
   Файл нічого не створює й нічого не прибирає — лише переписує рядок у
   наявному текстовому вузлі. Будь-яке падіння ловиться `try/catch`, і сторінка
   лишається рівно такою, якою її намалював js/module.js.

   ⚠ ЧОГО ТУТ СВІДОМО НЕМАЄ: `aria-label="Навігація між модулями"` на
   `#moduleNav` стоїть у РОЗМІТЦІ всіх 23 уроків (контент заморожений, К-29, і
   заміна атрибута в перелік дозволених механічних пасів не входить). Це рядок
   для реєстру хвостів, не дефект цього файла.
   ========================================================================== */
(function (global) {
  "use strict";

  /* Лукахед на кириличну літеру — щоб «модулями» (воно є в aria-label розмітки,
     а теоретично може приїхати й у текст) не перетворилось на «урокуми».
     Суфікс → закінчення: «Модуль» → «Урок», «Модуля» → «Уроку»,
     «модулі» → «уроки», «модулів» → «уроків». */
  var RE = /(М|м)одул(ів|я|і|ь)(?![а-яіїєґА-ЯІЇЄҐʼ'’])/g;
  var END = { "ів": "ків", "я": "ку", "і": "ки", "ь": "к" };

  var HOSTS = ["#sidebarNav", "#moduleNav", "#completeTitle", "#aiaGate", "#ariaLive"];

  function swap(s) {
    return s.replace(RE, function (_, cap, suf) {
      return (cap === "М" ? "Уро" : "уро") + END[suf];
    });
  }

  function walk(host) {
    if (!host) return;
    var it = document.createTreeWalker(host, NodeFilter.SHOW_TEXT, null, false);
    var n;
    while ((n = it.nextNode())) {
      var v = n.nodeValue;
      if (v && v.indexOf("одул") >= 0) {
        var next = swap(v);
        if (next !== v) n.nodeValue = next;
      }
    }
  }

  function apply() {
    try {
      for (var i = 0; i < HOSTS.length; i++) walk(document.querySelector(HOSTS[i]));
    } catch (e) { /* словник не має права валити сторінку */ }
  }

  apply();

  if ("MutationObserver" in global) {
    try {
      /* Спостерігати доводиться ширше за самі хости: `#aiaGate` js/module.js
         СТВОРЮЄ і вставляє в `<main>` аж після відповіді Supabase, тож вузла,
         на який можна було б повісити спостерігач, спочатку не існує. Обхід
         залишається дешевим: п'ять невеликих піддерев, без діаграм і без прози. */
      new MutationObserver(apply).observe(document.body, {
        childList: true, subtree: true, characterData: true
      });
    } catch (e) { /* лишається страховка подіями нижче */ }
  }

  document.addEventListener("aia:progress", apply);
  document.addEventListener("aia:config-ready", apply);
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", apply);
})(window);
