/* ============================================================================
   012 · js/jira-mermaid.js — `state: { useMaxWidth: false }` ДЛЯ СТОРІНОК JIRA
   ----------------------------------------------------------------------------
   Підключається ТІЛЬКИ зі сторінок Jira, які малюють діаграми, і ТІЛЬКИ
   МІЖ `js/mermaid-theme.js` і `js/mermaid-init.js`.

   НАВІЩО
   ------
   `js/mermaid-theme.js` (010, D-05) вимикає `useMaxWidth` рівно для двох типів
   діаграм, бо на той момент на сайті вживались рівно два: `flowchart` (94) і
   `sequence` (6). У курсі «Jira з нуля» зʼявився третій — `stateDiagram-v2`
   (modules/jira-10.html і modules/jira-19.html). Без цього ключа Mermaid
   ставить таким SVG `width="100%"` + `max-width:<натуральна>px`, і діаграма не
   ПРОКРУЧУЄТЬСЯ, а пропорційно стискається разом із підписами: на 390 px
   ефективний кегль падає в рази (заміряно в 010 на 100 діаграмах — найгірший
   випадок 1,33 px). З `false` підпис завжди 14 px (`--fs-ui`), а горизонтальний
   скрол бере на себе `.ds-diag` / `pre.mermaid`.

   ЧОМУ ОБГОРТКА, А НЕ ПРАВКА `js/mermaid-theme.js`
   -----------------------------------------------
   Рішення власника 2026-10-01 (принцип І-0 «ізоляція — лише додавати»):
   `js/mermaid-theme.js` спільний для 66 сторінок трьох живих курсів і не
   змінюється. Ключ `state` для них нічого не змінив би (жодної state-діаграми
   там немає), але правило є правилом — тому ключ дописується тільки там, де
   він потрібен.

   ЧОМУ ПОРЯДОК ПІДКЛЮЧЕННЯ САМЕ ТАКИЙ
   -----------------------------------
   `js/mermaid-init.js` викликає `AIA.mermaidTheme.config()` не при
   завантаженні, а всередині `run()`, який чекає `document.fonts.ready`. Коли
   шрифти вже в кеші, цей проміс розвʼязується МІКРОЗАДАЧЕЮ — тобто `run()`
   може виконатись раніше, ніж браузер дотягне наступний `<script src>` із
   мережі. Отже обгортку не можна ставити ПІСЛЯ `mermaid-init.js`: ключ
   доїхав би із запізненням, і дві діаграми лишились би стиснутими, без жодної
   ознаки помилки. Перед `mermaid-init.js` — безпечно завжди.
   ========================================================================== */
(function (global) {
  "use strict";

  var T = global.AIA && global.AIA.mermaidTheme;
  if (!T || typeof T.config !== "function") return;   /* теми немає — нічого не робимо */

  var base = T.config;
  T.config = function () {
    var c = base.apply(this, arguments) || {};
    /* Ключ живе ОКРЕМО для кожного типу діаграми, тому дописування `state`
       не може зачепити ні `flowchart`, ні `sequence`. Наявне значення, якщо
       воно колись зʼявиться у спільній темі, не затирається. */
    if (!c.state) c.state = { useMaxWidth: false };
    else if (c.state.useMaxWidth === undefined) c.state.useMaxWidth = false;
    return c;
  };
})(window);
